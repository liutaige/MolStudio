const names = new Set(Object.keys(result.metafile.inputs).flatMap(path => {
  const match = /node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(path.replaceAll('\\', '/'));
  return match ? [match[1]] : [];
}));
const licenseDir = resolve(here, 'dist/licenses');
await mkdir(licenseDir, { recursive: true });
const rows = [], notices = [];
for (const name of [...names].sort()) {
  const directory = resolve(here, 'node_modules', name);
  const pkg = JSON.parse(await readFile(resolve(directory, 'package.json'), 'utf8'));
  const filenames = (await readdir(directory)).filter(name => /^(?:licen[sc]e|copying|notice)(?:[.-]|$)/i.test(name));
  const links = [];
  for (const filename of filenames) {
    const text = await readFile(resolve(directory, filename), 'utf8');
    const target = `${name.replaceAll('/', '__')}__${filename}`;
    await writeFile(resolve(licenseDir, target), text);
    links.push(`dist/licenses/${target}`);
    notices.push(`${name}@${pkg.version} — ${filename}\n${text}`);
  }
  if (!filenames.length && name.startsWith('@earendil-works/pi-')) {
    const target = `${name.replaceAll('/', '__')}__LICENSE.txt`;
    await writeFile(resolve(licenseDir, target), piLicense);
    links.push(`dist/licenses/${target}`);
    notices.push(`${name}@${pkg.version}\n${piLicense}`);
  }
  if (!links.length) throw new Error(`Missing third-party license for bundled package ${name}`);
  const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  const url = (repository || pkg.homepage || '').replace(/^github:/, 'https://github.com/').replace(/^git\+/, '').replace(/\.git$/, '')
    .replace(/^([\w.-]+\/[\w.-]+)$/, 'https://github.com/$1');
  rows.push(`| ${name}@${pkg.version} | ${pkg.license || 'See license'} | ${url ? `[Official source](${url})` : ''} | ${links.map(link => `[${link.split('/').at(-1)}](${link})`).join(', ')} |`);
}
await writeFile(resolve(here, 'THIRD_PARTY_NOTICES.md'), `# MolStudio agent runtime third-party notices

Generated by build.mjs from the packages actually included in dist/agent-runtime.js. These packages retain their own licenses; MolStudio does not relicense them. The full license notices are included in dist/licenses and the combined dist/THIRD_PARTY_NOTICES.txt. Development dependencies such as esbuild are not part of this runtime bundle.

Pi's repository-level MIT notice is reproduced where the npm package does not include LICENSE: https://github.com/earendil-works/pi/blob/v1.5.0/LICENSE.

| Bundled package | License | Source | Full notice |
| --- | --- | --- | --- |
${rows.join('\n')}
`);
await writeFile(resolve(here, 'dist/THIRD_PARTY_NOTICES.txt'), notices.join('\n\n========================================\n\n'));
