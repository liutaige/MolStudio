import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';

const here = dirname(fileURLToPath(import.meta.url));
const result = await build({
  entryPoints: [resolve(here, 'runtime.js')],
  outfile: resolve(here, 'dist/agent-runtime.js'),
  bundle: true,
  platform: 'browser',
  target: 'safari17',
  format: 'iife',
  globalName: 'MolStudioAgentRuntime',
  minify: true,
  legalComments: 'linked',
  metafile: true,
  logLevel: 'info',
});

// npm's Pi packages omit LICENSE files; their repository-level MIT license
// covers these packages. Keep the notice beside the distributable bundle.
